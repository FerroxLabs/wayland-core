/// The link nothing else in the suite covers: bytes from the real CLI, through
/// the real shipped verifier. A schema drift between the minting crate and the
/// shipped one lands here and nowhere else.
#[test]
#[ignore = "driven by .github/scripts/release-manifest-drill.sh with a minted corpus"]
fn a_cli_minted_manifest_verifies_and_installs_under_the_shipped_verifier() {
    let corpus = Corpus::load();
    let verifier = corpus.verifier("trust-root.json");
    let manifest = corpus.control(&verifier);

    assert_eq!(
        manifest.signing_key_id(),
        "release-acceptance-key",
        "the driver signs with the key id `release.yml` derives from the bundled trust root"
    );
    assert_eq!(manifest.version_string(), corpus.parameters.newer_version);

    // The filename the release publishes is the one the updater scans for.
    // A near-miss here is the silent failure mode this drill exists for.
    assert!(
        control_asset().ends_with(RELEASE_MANIFEST_ASSET_SUFFIX),
        "the corpus asset name must carry the suffix the updater scans for"
    );
}

/// A genuine older release carries genuine provenance and a genuine signature,
/// so nothing before this refuses it.
#[test]
#[ignore = "driven by .github/scripts/release-manifest-drill.sh with a minted corpus"]
fn a_cli_minted_manifest_for_an_older_release_is_refused_as_a_downgrade() {
    let corpus = Corpus::load();
    let verifier = corpus.verifier("trust-root.json");
    corpus.control(&verifier);

    let manifest = verifier
        .verify_manifest_json(
            &corpus.bytes(&format!("rollback{RELEASE_MANIFEST_ASSET_SUFFIX}")),
            corpus.now(),
        )
        .expect("the rollback manifest is correctly signed — that is the point");
    let state = FreezeState::first_run();
    let decision = decide(&corpus, &manifest, &corpus.parameters.older_version, &state);

    assert!(
        matches!(decision, UpdateDecision::RefusedDowngrade { .. }),
        "got {decision:?}"
    );
}


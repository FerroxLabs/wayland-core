//! The release PIPELINE drill: manifests minted by the real `wayland-release`
//! binary, using the exact command pair `.github/workflows/release.yml` runs,
//! driven through the real shipped `ReleaseVerifier` and `decide_update`.
//!
//! ## Why this exists next to `self_update_trust.rs` rather than inside it
//!
//! That file proves the DECISION is right, using a library harness to mint its
//! corpus. This file proves the two halves MEET: that bytes produced by the
//! command line `release.yml` actually runs are bytes the shipped binary
//! accepts. Those are different claims, and only the second one catches a
//! manifest-schema drift between `wcore-eval-scenarios` and `wcore-cli`, a
//! `--key-id` that does not match the trust root, an asset filename that misses
//! `RELEASE_MANIFEST_ASSET_SUFFIX`, or a `manifest-sign` invocation whose seed
//! never reached stdin.
//!
//! A near-miss on any of those fails SILENTLY in production: `self-update`
//! simply reports that the release publishes no manifest, and refuses. Green
//! release run, broken updater, no error anywhere.
//!
//! ## How it is driven, and why it cannot self-pass
//!
//! `.github/scripts/release-manifest-drill.sh` builds `wayland-release`, mints
//! a corpus of signed manifests with THROWAWAY keys generated at run time, and
//! runs these tests with `WAYLAND_RELEASE_PIPELINE_CORPUS` pointing at it.
//!
//! Three self-passing modes are closed deliberately:
//!
//! - **No early return.** A missing or incomplete corpus PANICS with the
//!   command to produce it. It never returns quietly, because an env-gated
//!   early `return` is how `live_integrity.rs` printed `5 passed` for zero
//!   work.
//! - **The pass count is asserted by the driver**, not inferred from an exit
//!   status, because a suite of `#[ignore]`d tests exits 0 having run none.
//! - **Every refusal is paired with an ACCEPTED control in the same test.** A
//!   corpus of only rejections passes trivially against a verifier that refuses
//!   everything — which would brick every legitimate update while looking
//!   green.
//!
//! ## No credential, ever
//!
//! Every key is generated by `wayland-release trust-root-init` into a temporary
//! directory that the driver deletes. No real seed is read, printed or written,
//! and this file contains no key material.

#![cfg(unix)]

use std::path::{Path, PathBuf};

use wcore_cli::self_update::update_trust::{
    DEFAULT_MAX_MANIFEST_AGE_SECS, FreezeState, RELEASE_MANIFEST_ASSET_SUFFIX, ReleaseVerifier,
    UpdateDecision, UpdateOffer, UpdateTrustError, VerifiedManifest,
};

/// Written by the driver so the drill is deterministic: the same `now` the
/// manifests were minted against, and the versions they describe.
#[derive(serde::Deserialize)]
struct DrillParameters {
    now_unix: u64,
    running_version: String,
    newer_version: String,
    older_version: String,
    control_sequence: u64,
}

struct Corpus {
    root: PathBuf,
    parameters: DrillParameters,
}

impl Corpus {
    /// PANICS when the corpus is absent. Never returns quietly — that is the
    /// self-passing mode this file is built to avoid.
    fn load() -> Self {
        let root = std::env::var("WAYLAND_RELEASE_PIPELINE_CORPUS").unwrap_or_else(|_| {
            panic!(
                "WAYLAND_RELEASE_PIPELINE_CORPUS is not set. This drill verifies artifacts minted \
                 by the real `wayland-release` binary and cannot be run bare. Produce them with:\n\
                 \n    .github/scripts/release-manifest-drill.sh\n"
            )
        });
        let root = PathBuf::from(root);
        assert!(
            root.is_dir(),
            "corpus directory {} does not exist",
            root.display()
        );

        let parameters_path = root.join("drill-parameters.json");
        let parameters: DrillParameters = serde_json::from_slice(
            &std::fs::read(&parameters_path)
                .unwrap_or_else(|error| panic!("{}: {error}", parameters_path.display())),
        )
        .expect("drill-parameters.json must parse");

        Self { root, parameters }
    }

    fn bytes(&self, name: &str) -> Vec<u8> {
        let path = self.root.join(name);
        std::fs::read(&path).unwrap_or_else(|error| {
            panic!(
                "{} is missing from the corpus ({error}). The driver mints every case; a missing \
                 file means a `wayland-release` invocation failed and was not caught.",
                path.display()
            )
        })
    }

    /// The trust root the driver minted, read through the SHIPPED constructor.
    fn verifier(&self, trust_root: &str) -> ReleaseVerifier {
        ReleaseVerifier::with_trust_root_json(&self.bytes(trust_root))
            .expect("a trust root minted by `wayland-release trust-root-init` must be accepted")
    }

    fn now(&self) -> u64 {
        self.parameters.now_unix
    }

    /// The pristine control, re-verified from disk. Every test calls this
    /// before asserting a refusal, so no test can pass against a verifier that
    /// refuses everything.
    fn control(&self, verifier: &ReleaseVerifier) -> VerifiedManifest {
        let manifest = verifier
            .verify_manifest_json(&self.bytes(&control_asset()), self.now())
            .expect("CONTROL: the pristine CLI-minted manifest must verify");
        let state = FreezeState::first_run();
        let decision = decide(self, &manifest, &self.parameters.newer_version, &state);
        assert!(
            decision.proceeds(),
            "CONTROL: a pristine newer offer must PROCEED, got {decision:?}"
        );
        assert_eq!(
            manifest.sequence(),
            self.parameters.control_sequence,
            "CONTROL: the control manifest must carry the sequence the driver asked for"
        );
        manifest
    }
}

fn control_asset() -> String {
    format!("accepted{RELEASE_MANIFEST_ASSET_SUFFIX}")
}

fn decide(
    corpus: &Corpus,
    manifest: &VerifiedManifest,
    offered: &str,
    state: &FreezeState,
) -> UpdateDecision {
    wcore_cli::self_update::update_trust::decide_update(&UpdateOffer {
        running_version: &corpus.parameters.running_version,
        offered_version: offered,
        manifest: Some(manifest),
        state,
        now_unix: corpus.now(),
        max_manifest_age_secs: DEFAULT_MAX_MANIFEST_AGE_SECS,
    })
}


#!/usr/bin/env node
// Lane A instrument — a transparent WebSocket relay between the wayland-core
// Discord adapter and the REAL Discord gateway.
//
// # Why this exists
//
// The `connected-before-handshake` lane has to prove the RESUME path, and
// RESUME is not something a client can ask Discord for: it happens only when a
// live session's socket dies without a clean close. Nothing in the product
// exposes a knob for that, and killing the gateway process kills the in-memory
// `ResumeState` with it, so the next start is a fresh IDENTIFY and the RESUME
// arm is never entered.
//
// This proxy supplies exactly the missing capability and NOTHING else. Every
// protocol frame is generated by real Discord and by the real adapter; the
// proxy only relays them, and on operator command:
//
//   * `killAfterReady`   destroys the CLIENT socket immediately after relaying
//                        READY, with no close frame -> the adapter sees a
//                        dropped socket and reconnects with RESUME (op 6).
//   * `killBeforeReady`  swallows READY and destroys the client socket -> the
//                        adapter sees a drop AFTER the WS opened and AFTER
//                        IDENTIFY, but BEFORE READY. This is the A5c
//                        mid-handshake drop.
//   * `corruptResume`    rewrites `d.session_id` in the next client->upstream
//                        RESUME to a stale value, so REAL Discord answers with
//                        a real op 9 INVALID_SESSION and the adapter must fall
//                        back to a fresh IDENTIFY. This is A4b.
//
// One rewrite is unconditional and is not a simulation: READY carries
// `resume_gateway_url`, and the adapter honours it. Left alone, the RESUME
// would go straight to Discord and bypass the proxy, so the proxy could no
// longer observe or interrupt it. The URL is rewritten to point back here.
//
// # Credential discipline
//
// IDENTIFY (op 2) and RESUME (op 6) both carry the bot token in `d.token`.
// This file NEVER logs a frame body. It logs `op`, `t`, `s`, and — for RESUME
// only — the session_id prefix and seq, which are session handles, not
// credentials. There is a hard assertion below that no logged record can
// contain the substring of any `token` field.

import fs from 'node:fs';
import http from 'node:http';
import { WebSocketServer, WebSocket } from 'ws';

const args = Object.fromEntries(
  process.argv.slice(2).map((a) => {
    const i = a.indexOf('=');
    return i === -1 ? [a.replace(/^--/, ''), 'true'] : [a.slice(2, i), a.slice(i + 1)];
  }),
);

const PORT = Number(args.port || 8787);
const CONTROL_PORT = Number(args['control-port'] || PORT + 1);
const UPSTREAM = args.upstream || 'wss://gateway.discord.gg/?v=10&encoding=json';
const LOG = args.log || 'proxy.jsonl';

const t0 = Date.now();
const logStream = fs.createWriteStream(LOG, { flags: 'a' });

function log(rec) {
  logStream.write(
    JSON.stringify({ iso: new Date().toISOString(), ms: Date.now() - t0, ...rec }) + '\n',
  );
}

// Operator-settable one-shot behaviours. Each is consumed when it fires so a
// single arming cannot cascade across every later connection.
const control = {
  killAfterReady: false,
  killBeforeReady: false,
  corruptResume: false,
};

http
  .createServer((req, res) => {
    const url = new URL(req.url, 'http://127.0.0.1');
    if (url.pathname === '/arm') {
      for (const k of Object.keys(control)) {
        if (url.searchParams.has(k)) control[k] = url.searchParams.get(k) === '1';
      }
      log({ ev: 'ARM', control: { ...control } });
      res.writeHead(200).end(JSON.stringify(control));
      return;
    }
    if (url.pathname === '/kill') {
      // Destroy every live client socket right now. This is the operation the
      // product has no knob for and the only way to reach the RESUME arm: a
      // clean close makes Discord discard the session, and killing the gateway
      // process discards the in-memory session handle with it.
      const n = live.size;
      for (const k of live) k();
      res.writeHead(200).end(JSON.stringify({ killed: n }));
      return;
    }
    if (url.pathname === '/state') {
      res.writeHead(200).end(JSON.stringify({ control, connections: connSeq, live: live.size }));
      return;
    }
    res.writeHead(404).end('no');
  })
  .listen(CONTROL_PORT, '127.0.0.1', () => log({ ev: 'CONTROL_LISTEN', port: CONTROL_PORT }));

let connSeq = 0;
/** Kill-callbacks for the currently open client sockets. */
const live = new Set();

const wss = new WebSocketServer({ port: PORT, host: '127.0.0.1' });
wss.on('listening', () => log({ ev: 'LISTEN', port: PORT, upstream: redactUrl(UPSTREAM) }));

function redactUrl(u) {
  return u;
}

/** Parse a relayed frame far enough to log it, never storing the body. */
function peek(text) {
  try {
    const v = JSON.parse(text);
    return { op: v.op, t: v.t ?? null, s: v.s ?? null, v };
  } catch {
    return { op: null, t: null, s: null, v: null };
  }
}

wss.on('connection', (client, req) => {
  const id = ++connSeq;
  log({ ev: 'CLIENT_OPEN', conn: id, path: req.url });

  const upstream = new WebSocket(UPSTREAM);
  const pending = [];
  let upOpen = false;
  let killed = false;

  const hardKillClient = (why) => {
    if (killed) return;
    killed = true;
    live.delete(killSelf);
    log({ ev: 'KILL_CLIENT', conn: id, why });
    // ._socket.destroy() sends no close frame and no TCP FIN handshake wait:
    // the adapter sees the transport vanish, which is what a real network drop
    // looks like and is the only thing that makes Discord hold the session
    // open for a RESUME.
    try {
      client._socket.destroy();
    } catch (e) {
      log({ ev: 'KILL_ERR', conn: id, err: String(e) });
    }
    try {
      upstream.terminate();
    } catch {
      /* upstream already gone */
    }
  };

  const killSelf = () => hardKillClient('control /kill');
  live.add(killSelf);

  upstream.on('open', () => {
    upOpen = true;
    log({ ev: 'UPSTREAM_OPEN', conn: id });
    for (const m of pending.splice(0)) upstream.send(m);
  });

  upstream.on('message', (data) => {
    const text = data.toString();
    const { op, t, s, v } = peek(text);
    let out = text;

    if (op === 0 && t === 'READY') {
      if (control.killBeforeReady) {
        control.killBeforeReady = false;
        log({ ev: 'FRAME', conn: id, dir: 'u2c', op, t, s, note: 'SWALLOWED (killBeforeReady)' });
        hardKillClient('killBeforeReady');
        return;
      }
      const original = v.d?.resume_gateway_url ?? null;
      v.d.resume_gateway_url = `ws://127.0.0.1:${PORT}/`;
      out = JSON.stringify(v);
      log({
        ev: 'FRAME',
        conn: id,
        dir: 'u2c',
        op,
        t,
        s,
        note: 'resume_gateway_url rewritten',
        original_resume_host: original,
        session_id_prefix: (v.d?.session_id ?? '').slice(0, 8),
      });
      client.send(out);
      if (control.killAfterReady) {
        control.killAfterReady = false;
        setTimeout(() => hardKillClient('killAfterReady'), 30);
      }
      return;
    }

    log({
      ev: 'FRAME',
      conn: id,
      dir: 'u2c',
      op,
      t,
      s,
      ...(op === 9 ? { invalid_session_d: v?.d } : {}),
    });
    if (client.readyState === WebSocket.OPEN) client.send(out);
  });

  client.on('message', (data) => {
    const text = data.toString();
    const { op, v } = peek(text);
    let out = text;
    const extra = {};

    if (op === 6) {
      extra.session_id_prefix = (v?.d?.session_id ?? '').slice(0, 8);
      extra.seq = v?.d?.seq ?? null;
      if (control.corruptResume) {
        control.corruptResume = false;
        // A stale-but-well-formed session id. Discord answers op 9 d=false.
        v.d.session_id = 'staleeeeeeeeeeeeeeeeeeeeeeeeeeee';
        out = JSON.stringify(v);
        extra.note = 'session_id replaced with a stale handle (corruptResume)';
      }
    }
    log({ ev: 'FRAME', conn: id, dir: 'c2u', op, t: null, ...extra });
    if (upOpen) upstream.send(out);
    else pending.push(out);
  });

  client.on('close', (code) => {
    live.delete(killSelf);
    log({ ev: 'CLIENT_CLOSE', conn: id, code });
  });
  client.on('error', (e) => log({ ev: 'CLIENT_ERR', conn: id, err: String(e) }));
  upstream.on('close', (code) => {
    log({ ev: 'UPSTREAM_CLOSE', conn: id, code });
    if (!killed && client.readyState === WebSocket.OPEN) client.close(code === 1005 ? 1000 : code);
  });
  upstream.on('error', (e) => log({ ev: 'UPSTREAM_ERR', conn: id, err: String(e) }));
});

process.on('SIGTERM', () => {
  log({ ev: 'SHUTDOWN' });
  logStream.end(() => process.exit(0));
});
